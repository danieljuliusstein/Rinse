/** Run against an EMPTY disposable PocketBase with repository migrations and hooks. */
import assert from 'node:assert/strict'
import PocketBase from '../rinse-api/node_modules/pocketbase/dist/pocketbase.es.mjs'
const url = process.env.PB_TEST_URL || 'http://127.0.0.1:8099'
assert.match(url, /^http:\/\/(127\.0\.0\.1|localhost):/, 'Only disposable local test databases are allowed')
const pb = new PocketBase(url); pb.autoCancellation(false)
await pb.collection('_superusers').authWithPassword('test@rinse.test', 'RinseLocalTestOnly123')
const suffix = Date.now().toString(36)
async function org(name) { return pb.collection('organizations').create({ name, slug: `${name}-${suffix}`, plan: 'free', subscription_status: 'none' }) }
const command = body => pb.send('/api/rinse/billing', { method: 'POST', body })
try {
const free = await org('free')
const user = await pb.collection('users').create({ email: `free-${suffix}@example.com`, password: 'RinseLocalTestOnly123', passwordConfirm: 'RinseLocalTestOnly123', organization_id: free.id })
const client = new PocketBase(url); client.autoCancellation(false)
await client.collection('users').authWithPassword(user.email, 'RinseLocalTestOnly123')
await assert.rejects(() => client.collection('organizations').update(free.id, { plan: 'founding', founding_member: true }))
await assert.rejects(() => client.collection('organizations').update(free.id, { subscription_status: 'active', current_period_end: '2030-01-01' }))
await assert.rejects(() => client.collection('users').update(user.id, { organization_id: '' }))
await assert.rejects(() => client.send('/api/rinse/billing', { method: 'POST', body: { action: 'founding', orgId: free.id } }))
const customer = await client.collection('clients').create({ organization_id: free.id, name: 'Sample Client' })
const pkg = await client.collection('packages').create({ organization_id: free.id, name: 'Full Detail', base_price: 180, active: true })
const base = { package_id: pkg.id, vehicle_type: 'sedan', revenue: 180, organization_id: free.id, client_id: customer.id, date: '2026-10-01', status: 'scheduled', location_type: 'mobile' }
const jobs = await Promise.allSettled(Array.from({ length: 12 }, () => client.collection('jobs').create(base)))
const successes = jobs.filter(r => r.status === 'fulfilled').map(r => r.value)
if (successes.length !== 5) console.log(jobs.filter(r => r.status === 'rejected').map(r => r.reason.response))
assert.equal(successes.length, 5, 'concurrent job limit')
await client.collection('jobs').update(successes[0].id, { status: 'completed' })
const extra = await client.collection('jobs').create(base)
await assert.rejects(() => client.collection('jobs').update(successes[0].id, { status: 'in_progress' }))
const invoice = await client.collection('invoices').create({ organization_id: free.id, job_id: extra.id, client_id: customer.id, invoice_number: `INV-${suffix}`, subtotal: 180, total: 180, balance_due: 180, status: 'sent' })
await client.collection('portal_tokens').create({ organization_id: free.id, client_id: customer.id, job_id: extra.id, scope: 'invoice', token: `invoice-token-${suffix}`, expires_at: '2027-01-01' })
await assert.rejects(() => client.collection('portal_tokens').create({ organization_id: free.id, client_id: customer.id, job_id: extra.id, scope: 'full', token: `full-token-${suffix}`, expires_at: '2027-01-01' }))
console.log('PASS: Free concurrent job cap, reopen cap, invoices, invoice links, protected fields')
await pb.collection('organizations').update(free.id, { plan: 'starter', subscription_status: 'active', current_period_end: '2030-01-01' })
await client.collection('jobs').create(base)
await pb.collection('organizations').update(free.id, { plan: 'free', subscription_status: 'none' })
await client.collection('jobs').update(extra.id, { notes: 'Existing records remain editable' })
await assert.rejects(() => client.collection('jobs').create(base))
console.log('PASS: over-limit downgrade preserves and permits existing work')
const orgs = []
for (let i = 0; i < 105; i++) orgs.push(await org(`early-${i}`))
const reservations = await Promise.all(orgs.map(o => command({ action: 'reserve', orgId: o.id, provider: 'stripe' })))
assert.equal(reservations.filter(r => r.plan === 'early').length, 100)
const repeats = await Promise.all(Array.from({ length: 12 }, () => command({ action: 'reserve', orgId: orgs[0].id, provider: 'stripe' })))
assert.ok(repeats.every(r => r.id === reservations[0].id && r.generation === reservations[0].generation))
await assert.rejects(() => command({ action: 'reserve', orgId: orgs[0].id, provider: 'apple' }))
const sync = { action: 'sync', orgId: orgs[0].id, provider: 'stripe', subscriptionId: 'sub_test', plan: 'early', status: 'active', paid: true, periodEnd: '2030-01-01T00:00:00Z', eventId: `paid-${suffix}` }
await Promise.all(Array.from({ length: 10 }, () => command(sync)))
assert.equal((await pb.collection('early_allocations').getList(1, 1)).totalItems, 1)
await command({ ...sync, eventId: `cancel-${suffix}`, cancelAtPeriodEnd: true })
assert.equal((await pb.collection('organizations').getOne(orgs[0].id)).plan, 'early')
await command({ ...sync, eventId: `ended-${suffix}`, status: 'canceled' })
assert.equal((await pb.collection('organizations').getOne(orgs[0].id)).plan, 'free')
await assert.rejects(() => command({ ...sync, eventId: `reclaim-${suffix}` }))
await command({ action: 'release', orgId: orgs[1].id, generation: reservations[1].generation })
const next = await org('released'); assert.equal((await command({ action: 'reserve', orgId: next.id, provider: 'stripe' })).plan, 'early')
console.log('PASS: 100 Early reservations, concurrency, provider exclusion, payment allocation, idempotency, cancellation, no restoration, release')
const founders = []
for (let i = 0; i < 21; i++) founders.push(await org(`founder-${i}`))
const grants = await Promise.allSettled(founders.map(o => command({ action: 'founding', orgId: o.id })))
assert.equal(grants.filter(r => r.status === 'fulfilled').length, 20)
console.log('PASS: Founding restricted to superuser and concurrent 20-account cap')
await pb.collection('organizations').update(free.id, { stripe_connect_account_id: 'acct_operator' })
const payment = { invoiceId: invoice.id, accountId: 'acct_operator', paymentId: 'ch_test', amount: 18000, refunded: 0 }
const reconcile = data => pb.send('/api/rinse/reconcile-payment', { method: 'POST', body: data })
await assert.rejects(() => reconcile({ ...payment, accountId: 'acct_wrong' }))
await Promise.all(Array.from({ length: 10 }, () => reconcile(payment)))
assert.equal((await pb.collection('invoices').getOne(invoice.id)).amount_paid, 180)
await reconcile({ ...payment, refunded: 5000 }); await reconcile(payment)
const refunded = await pb.collection('invoices').getOne(invoice.id)
assert.equal(refunded.amount_paid, 130); assert.equal(refunded.balance_due, 50); assert.equal(refunded.status, 'partial')
console.log('PASS: connected operator identity, concurrent payment idempotency, partial refunds, stale events')
} catch (e) { console.error(e.response || e); process.exitCode = 1 }
